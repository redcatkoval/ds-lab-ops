import числа from "virtual:ds-lab/lint"

/**
 * Откуда числа и когда — на экране всегда, а не только при отказе.
 * Прогон линтера основной, снимок запасной; третий случай — нет ни
 * того, ни другого, и тогда страница говорит об этом.
 */
export const Источник = () => {
  if (числа.источник === "прогон") {
    return <>прогон линтера · {числа.снят}</>
  }
  if (числа.источник === "снимок") {
    return (
      <span className="text-ui-fg-error">
        снимок от {числа.снят} · прогон не удался:{" "}
        {числа.почему?.split("\n")[0]}
      </span>
    )
  }
  return (
    <span className="text-ui-fg-error">
      чисел нет: {числа.почему?.split("\n")[0]}
    </span>
  )
}
