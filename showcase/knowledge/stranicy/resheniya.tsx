import корпус from "virtual:ds-lab/corpus"

import { Плашки, Плитка, Пояснение, Страница, Таблица } from "../_shell"

const действует = корпус.решения.filter((р) => р.состояние === "действует")

export const Решения = () => (
  <Страница title="Решения" источник={<>поля разметки · DEC-020</>}>
    <Пояснение>
      Принятые решения: что мы условились считать верным и почему. Каждое
      живёт файлом в `ds-ops/decisions/`, и на них ссылаются контракт,
      правила линтера и вопросы. Данные — из полей `**Состояние:**`
      и `**Дата.**`. Смотреть, чтобы понять, на чём стоит нынешнее
      устройство: правило без решения — просто чей-то вкус.
    </Пояснение>

    <Плашки>
      <Плитка что="решений" сколько={корпус.решения.length} />
      <Плитка что="действуют" сколько={действует.length} />
      <Плитка
        что="частично заменены"
        сколько={корпус.решения.length - действует.length}
        чем="DEC-002 по DEC-009"
      />
      <Плитка
        что="первое"
        сколько={корпус.решения[0]?.дата?.slice(0, 7) ?? "—"}
        чем={корпус.решения[0]?.код}
      />
    </Плашки>

    <Таблица
      шапка={["решение", "состояние", "дата"]}
      строки={корпус.решения.map((р) => [
        <>
          <span className="font-mono">{р.код}</span>{" "}
          {р.заголовок.replace(/^DEC-\d+\.\s*/, "")}
        </>,
        р.состояние === "действует" ? (
          <span>действует</span>
        ) : (
          <span className="text-ui-fg-error">{р.состояние}</span>
        ),
        <span className="text-ui-fg-muted">{р.дата}</span>,
      ])}
    />
  </Страница>
)
