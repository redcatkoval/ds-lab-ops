import { useState } from "react"
import корпус from "virtual:ds-lab/corpus"

import { Плашки, Плитка, Пояснение, Страница, Таблица } from "../_shell"

type Разрез = "адресат" | "предмет"

const открытые = корпус.вопросы.filter((в) => в.состояние === "открыт")

const сгруппировать = (по: Разрез) => {
  const м = new Map<string, typeof корпус.вопросы>()
  for (const в of корпус.вопросы) {
    const ключ = (по === "адресат" ? в.адресат : в.предмет) ?? "не размечен"
    м.set(ключ, [...(м.get(ключ) ?? []), в])
  }
  return [...м.entries()].sort((a, b) => b[1].length - a[1].length)
}

export const Вопросы = () => {
  const [разрез, setРазрез] = useState<Разрез>("адресат")
  const группы = сгруппировать(разрез)

  return (
    <Страница
      title="Вопросы"
      источник={<>поля разметки · DEC-020, DEC-022</>}
    >
      <Пояснение>
        То, что измерением не решается: вопросы, на которые нужен ответ
        человека. Два разреза — к какой области относится вопрос
        и о чём он. Данные берутся из полей `**Адресат:**`
        и `**Предмет:**` в самих файлах; проза вопросов не разбирается
        и сюда не попадает. Смотреть, чтобы увидеть, где накопилось:
        область с длинным списком — это область, где мы много меряем
        и мало спрашиваем.
      </Пояснение>

      <Плашки>
        <Плитка что="всего" сколько={корпус.вопросы.length} />
        <Плитка что="открыто" сколько={открытые.length} />
        <Плитка что="решено" сколько={корпус.вопросы.length - открытые.length} />
        <Плитка что="разрезов" сколько={2} чем="адресат и предмет" />
      </Плашки>

      <div className="flex gap-2">
        {(["адресат", "предмет"] as const).map((р) => (
          <button
            key={р}
            type="button"
            onClick={() => setРазрез(р)}
            className={`border-ui-border-base txt-compact-small rounded-lg border px-3 py-1.5 ${
              разрез === р ? "bg-ui-bg-base-pressed" : "bg-ui-bg-base"
            }`}
          >
            по {р === "адресат" ? "адресату" : "предмету"}
          </button>
        ))}
      </div>

      {группы.map(([ключ, список]) => (
        <div key={ключ} className="flex flex-col gap-2">
          <h2 className="txt-compact-small-plus">
            {ключ}{" "}
            <span className="text-ui-fg-muted">
              · {список.length}, открытых{" "}
              {список.filter((в) => в.состояние === "открыт").length}
            </span>
          </h2>
          <Таблица
            шапка={["вопрос", "состояние", разрез === "адресат" ? "предмет" : "адресат", "дата"]}
            строки={список.map((в) => [
              <>
                <span className="font-mono">{в.код}</span>{" "}
                {в.заголовок.replace(/^Q-\d+\.\s*/, "")}
              </>,
              в.состояние === "открыт" ? (
                <span>открыт</span>
              ) : (
                <span className="text-ui-fg-muted">{в.состояние}</span>
              ),
              (разрез === "адресат" ? в.предмет : в.адресат) ?? "—",
              <span className="text-ui-fg-muted">{в.дата}</span>,
            ])}
          />
        </div>
      ))}
    </Страница>
  )
}
