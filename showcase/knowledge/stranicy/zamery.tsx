import файлы from "virtual:ds-lab/files"

import { Измерения, type Файлы } from "../_dataset"
import { Плашки, Плитка, Пояснение, Страница, размер } from "../_shell"

// Содержимое — по требованию; размеры и даты замеров приходят
// со стороны Node, иначе eager-импорт положил бы файлы в бандл.
const карты = import.meta.glob("../../../map/*.json", {
  query: "?raw",
  import: "default",
}) as Файлы
const токены = import.meta.glob("../../../tokens/*.json", {
  query: "?raw",
  import: "default",
}) as Файлы

const путьРазмеры = (каталог: "map" | "tokens") =>
  Object.fromEntries(
    Object.entries(файлы.размеры[каталог]).map(([имя, б]) => [
      `../../${каталог}/${имя}`,
      б,
    ])
  )
const путьДаты = (каталог: "map" | "tokens") =>
  Object.fromEntries(
    Object.entries(файлы.даты[каталог]).map(([имя, д]) => [
      `../../${каталог}/${имя}`,
      д.замер,
    ])
  )

const всего = [
  ...Object.values(файлы.размеры.map),
  ...Object.values(файлы.размеры.tokens),
].reduce((a, b) => a + b, 0)
const датыВсе = [
  ...Object.values(файлы.даты.map),
  ...Object.values(файлы.даты.tokens),
]
  .map((д) => д.замер)
  .filter(Boolean) as string[]

export const Замеры = () => (
  <Страница
    title="Замеры"
    источник={<>ds-ops/map/ и ds-ops/tokens/ · только измерения</>}
  >
    <Пояснение>
      Сырые измерения, из которых выведено всё остальное: обходы кода
      и слепки токенов. Здесь нет оценок — по правилу 8 в этих файлах
      только то, что померено, а выводы живут в решениях. Смотреть,
      когда нужно проверить чужое утверждение: у каждого файла стоит
      дата обхода, и если она старая — число из него тоже старое.
    </Пояснение>

    <Плашки>
      <Плитка что="файлов" сколько={датыВсе.length} />
      <Плитка что="данных" сколько={размер(всего)} />
      <Плитка что="самый ранний обход" сколько={датыВсе.sort()[0] ?? "—"} />
      <Плитка
        что="самый поздний"
        сколько={датыВсе.sort()[датыВсе.length - 1] ?? "—"}
      />
    </Плашки>

    <h2 className="txt-compact-small-plus">Карты: обходы кода</h2>
    <Измерения файлы={карты} размеры={путьРазмеры("map")} даты={путьДаты("map")} />

    <h2 className="txt-compact-small-plus">Токены: слепки значений</h2>
    <Измерения
      файлы={токены}
      размеры={путьРазмеры("tokens")}
      даты={путьДаты("tokens")}
    />
  </Страница>
)
